# Turn a saved AutoDrive ROUTE export (routesManager, or a debug capture's pre/post.xml) into the
# harness's graph_data.lua. The config exporter cannot read these: a route file separates its values
# with ";" where the savegame config uses ",", and its links are 1-based indices into its own list.
#
# This is what lets the harness run against the network a fault was actually seen in, instead of
# against my copy - which is how a whole day went into testing a junction that was never broken.
import sys, re
src, out = sys.argv[1], sys.argv[2]
s = open(src, encoding="utf8", errors="ignore").read()

def arr(tag):
    m = re.search(r"<%s>(.*?)</%s>" % (tag, tag), s, re.S)
    return m.group(1).split(";") if m else []

X = [float(v) for v in arr("x") if v.strip() != ""]
Y = [float(v) for v in arr("y") if v.strip() != ""]
Z = [float(v) for v in arr("z") if v.strip() != ""]
outs = [[int(v) for v in o.split(",") if v.strip() not in ("", "-1", "0")] for o in arr("out")]
# The file's OWN incoming list, in its own order. Rebuilding it from `out` loses both the order and
# anything asymmetric - a point wired to itself vanishes entirely, which is how 19 of them went
# unseen until AutoDrive drew them.
ins  = [[int(v) for v in o.split(",") if v.strip() not in ("", "-1", "0")] for o in arr("in")]
fl = [int(float(v)) for v in arr("flags") if v.strip() != ""]
n = len(X)
if len(Y) != n: Y = [0.0] * n
L = ["-- generated by export_route.py from " + src, "return {"]
for i in range(n):
    o = ",".join(str(v) for v in (outs[i] if i < len(outs) else []))
    inl = ",".join(str(v) for v in (ins[i] if i < len(ins) else []))
    L.append("  {id=%d,x=%.3f,y=%.3f,z=%.3f,flags=%d,out={%s},incoming={%s}}," %
             (i + 1, X[i], Y[i], Z[i], fl[i] if i < len(fl) else 0, o, inl))
L.append("}")
open(out, "w").write("\n".join(L) + "\n")
print("exported %d waypoints -> %s" % (n, out))

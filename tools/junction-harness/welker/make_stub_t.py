# A stand-in for Welker's fresh T at (-206.7, -925.9) (log.txt 2026-11-03 22:19): a two-lane N-S road, lane gap
# 3.7 m, and a two-lane side road from the east whose lanes end END_X (default -205.1, the road-runs handle:
# 1 m past the near lane), as road runs leaves them. Writes the harness's network format.
#   python welker/make_stub_t.py out.lua [end_x]
import sys
out = sys.argv[1]; end_x = float(sys.argv[2]) if len(sys.argv) > 2 else -205.1
cx, cz, L = -208.0, -926.2, 3.7
pts, links = [], []
def lane(coords):
    ids = []
    for (x, z) in coords:
        pts.append((x, z)); ids.append(len(pts))
    for a, b in zip(ids, ids[1:]): links.append((a, b))
    return ids
step = 4.0
n = 30
# near lane (east), heading north (-z); far lane (west), heading south (+z)
lane([(cx + L / 2, cz + 60 - i * step) for i in range(n + 1)])
lane([(cx - L / 2, cz - 60 + i * step) for i in range(n + 1)])
# side road: westbound lane in (north side, z = cz - L/2) ending at end_x; eastbound lane out starting at end_x
far = end_x + 60
lane([(far - i * (far - end_x) / 15, cz - L / 2) for i in range(16)])
lane([(end_x + i * (far - end_x) / 15, cz + L / 2) for i in range(16)])
outs = {i + 1: [] for i in range(len(pts))}
for a, b in links: outs[a].append(b)
with open(out, "w") as f:
    f.write("-- generated by make_stub_t.py\nreturn {\n")
    for i, (x, z) in enumerate(pts, 1):
        f.write("  {id=%d,x=%.3f,y=75.000,z=%.3f,flags=0,out={%s}},\n" % (i, x, z, ",".join(map(str, outs[i]))))
    f.write("}\n")
print("points", len(pts))

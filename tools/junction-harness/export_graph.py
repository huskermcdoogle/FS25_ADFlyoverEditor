import sys, xml.etree.ElementTree as ET
cfg, out = sys.argv[1], sys.argv[2]
root = ET.parse(cfg).getroot()
wp = root.find('.//waypoints')
def nums(tag):
    return [float(v) for v in wp.find(tag).text.strip().split(',')]
X, Y, Z = nums('x'), nums('y'), nums('z')
outs = [[int(v) for v in o.split(',') if v.strip() and v.strip() != '-1']
        for o in wp.find('out').text.strip().split(';')]
flags_el = wp.find('flags')
flags = [int(float(v)) for v in flags_el.text.strip().split(',')] if flags_el is not None else [0]*len(X)
n = len(X)
L = ["-- generated by export_graph.py", "return {"]
for i in range(n):
    o = ",".join(str(v) for v in outs[i]) if i < len(outs) else ""
    L.append(f"  {{id={i+1},x={X[i]:.3f},y={Y[i]:.3f},z={Z[i]:.3f},flags={flags[i] if i < len(flags) else 0},out={{{o}}}}},")
L.append("}")
open(out, "w").write("\n".join(L) + "\n")
print(f"exported {n} waypoints -> {out}")

"""Export an AutoDrive_config.xml to a Lua table WITH incoming lists and markers.

The junction harness exporter keeps only out lists and rebuilds incoming from them, which turns
every reverse link (out without incoming) into a normal one. The multiplayer probe needs the
network exactly as AutoDrive holds it, so this one copies both lists as stored.

    python export_full.py <AutoDrive_config.xml> <out.lua>
"""
import sys, xml.etree.ElementTree as ET

cfg, out = sys.argv[1], sys.argv[2]
root = ET.parse(cfg).getroot()
wp = root.find('.//waypoints')


def nums(tag):
    return [float(v) for v in wp.find(tag).text.strip().split(',')]


def lists(tag):
    el = wp.find(tag)
    if el is None or el.text is None:
        return []
    return [[int(v) for v in o.split(',') if v.strip() and v.strip() != '-1']
            for o in el.text.strip().split(';')]


X, Y, Z = nums('x'), nums('y'), nums('z')
outs, ins = lists('out'), lists('incoming')
flags_el = wp.find('flags')
flags = [int(float(v)) for v in flags_el.text.strip().split(',')] if flags_el is not None else [0] * len(X)

L = ["-- generated by tools/mp-probe/export_full.py", "return { wayPoints = {"]
for i in range(len(X)):
    o = ",".join(str(v) for v in outs[i]) if i < len(outs) else ""
    n = ",".join(str(v) for v in ins[i]) if i < len(ins) else ""
    f = flags[i] if i < len(flags) else 0
    L.append(f"  {{x={X[i]:.3f},y={Y[i]:.3f},z={Z[i]:.3f},flags={f},out={{{o}}},incoming={{{n}}}}},")
L.append("}, mapMarkers = {")
markers = root.find('.//mapmarker')
count = 0
if markers is not None:
    for m in markers:
        ident, name, group = m.find('id'), m.find('name'), m.find('group')
        if ident is None:
            continue
        nm = (name.text or "") if name is not None else ""
        gp = (group.text or "") if group is not None else ""
        L.append("  {id=%d,name=%s,group=%s}," % (int(float(ident.text)), repr(nm).replace("\\'", "'"), repr(gp)))
        count += 1
L.append("} }")
open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
print(f"exported {len(X)} waypoints, {count} markers -> {out}")

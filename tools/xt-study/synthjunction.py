# A CLEAN JUNCTION FOR THE TRAFFIC STUDY: two-lane roads (right-hand traffic, lanes 4 m apart, points
# every 5 m, 150 m long) meeting at (0, 0), not yet joined - the virgin site the editor's place and
# build start from. Written in the harness's network format (export_graph.py's), flat ground.
#   python synthjunction.py T out.lua      # three arms (west, east, south), all cut 6 m from the middle
#   python synthjunction.py X out.lua      # four arms, all cut 6 m from the middle
# x is east, z is south: heading east the right-hand side is +z, heading south it is -x.
import sys

kind, out = sys.argv[1], sys.argv[2]
HALF, STEP, LEN, CUT = 2.0, 5.0, 150.0, 6.0
pts = []          # [x, z, outs]

def lane(coords):
    """coords in travel order; links each to the next."""
    ids = []
    for (x, z) in coords:
        pts.append([x, z, []])
        ids.append(len(pts))
    for a, b in zip(ids, ids[1:]):
        pts[a - 1][2].append(b)

def span(a, b):
    """a .. b inclusive in STEP steps (either direction)."""
    n = int(round(abs(b - a) / STEP))
    return [a + (b - a) * i / n for i in range(n + 1)]

if kind == "T":
    lane([(x, HALF) for x in span(-LEN, -CUT)])                 # west arm, eastbound in
    lane([(x, -HALF) for x in span(-CUT, -LEN)])                # west arm, westbound out
    lane([(x, HALF) for x in span(CUT, LEN)])                   # east arm, eastbound out
    lane([(x, -HALF) for x in span(LEN, CUT)])                  # east arm, westbound in
    lane([(-HALF, z) for z in span(CUT, LEN)])                  # south arm, southbound out
    lane([(HALF, z) for z in span(LEN, CUT)])                   # south arm, northbound in
elif kind == "X":
    lane([(x, HALF) for x in span(-LEN, -CUT)])                 # west arm, eastbound in
    lane([(x, -HALF) for x in span(-CUT, -LEN)])                # west arm, westbound out
    lane([(x, HALF) for x in span(CUT, LEN)])                   # east arm, eastbound out
    lane([(x, -HALF) for x in span(LEN, CUT)])                  # east arm, westbound in
    lane([(-HALF, z) for z in span(CUT, LEN)])                  # south arm, southbound out
    lane([(HALF, z) for z in span(LEN, CUT)])                   # south arm, northbound in
    lane([(-HALF, z) for z in span(-LEN, -CUT)])                # north arm, southbound in
    lane([(HALF, z) for z in span(-CUT, -LEN)])                 # north arm, northbound out
else:
    sys.exit("kind must be T or X")

with open(out, "w") as f:
    f.write("-- generated by synthjunction.py (%s)\nreturn {\n" % kind)
    for i, (x, z, o) in enumerate(pts, 1):
        f.write("  {id=%d,x=%.3f,y=0.000,z=%.3f,flags=0,out={%s}},\n" % (i, x, z, ",".join(map(str, o))))
    f.write("}\n")
print("%s junction: %d points -> %s" % (kind, len(pts), out))
